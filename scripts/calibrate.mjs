#!/usr/bin/env node
// Re-estimate per-template difficulty (b) from consented anonymous responses and write public/js/calibration.js.
//
// Usage:
//   node scripts/calibrate.mjs                 # pull from the remote D1 (needs `wrangler login`), write calibration.js
//   node scripts/calibrate.mjs --local         # pull from the local D1 instead
//   node scripts/calibrate.mjs --dry-run       # print the result, write nothing
//   node scripts/calibrate.mjs --file rows.json  # read pre-aggregated rows instead of calling wrangler
//   node scripts/calibrate.mjs --min 50        # minimum responses per template (default 50)
//
// Method: for each template, rows are binned by the stored theta (0.1 steps). With theta treated as known
// and discrimination a (default 1.3) and guessing c = 1/options fixed, b is the penalised maximum-likelihood
// estimate of the 3PL (Fisher-scoring steps), with a weak N(b0, 1) prior on the current b0 so thin data
// cannot run away. b is clamped to [-3.5, 3.5]. Only templates with n >= --min are written; templates
// already in calibration.js keep their entry when they do not have enough new data.
//
// Caveat: stored theta comes from the current (nominal) difficulties, so this is a refinement, not an
// independent calibration. Re-run occasionally; large moves should be sanity-checked by hand.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'public/js/calibration.js');
const SQL =
  'SELECT template_id, ROUND(theta, 1) AS t, correct, n_options, COUNT(*) AS n FROM responses ' +
  'WHERE theta IS NOT NULL GROUP BY template_id, ROUND(theta, 1), correct, n_options';

// rows: [{ t, correct (0|1), n, c? }]; a row's own c (guessing floor) overrides the default. Returns { b, n }.
export function estimateB(rows, { b0, a = 1.3, c: c0 = 0.2, priorSd = 1 }) {
  const N = rows.reduce((s, r) => s + r.n, 0);
  const prec = 1 / (priorSd * priorSd);
  let b = b0;
  for (let iter = 0; iter < 60; iter++) {
    let g = -(b - b0) * prec; // gradient of log prior
    let info = prec; // Fisher information (prior + data)
    for (const r of rows) {
      const c = r.c ?? c0;
      const L = 1 / (1 + Math.exp(-a * (r.t - b)));
      const p = c + (1 - c) * L;
      const dp = -(1 - c) * a * L * (1 - L); // dp/db
      g += (r.n * (r.correct - p) * dp) / (p * (1 - p));
      info += (r.n * dp * dp) / (p * (1 - p));
    }
    const step = Math.max(-1, Math.min(1, g / info));
    b = Math.max(-3.5, Math.min(3.5, b + step));
    if (Math.abs(step) < 1e-7) break;
  }
  return { b: Math.round(b * 100) / 100, n: N };
}

// binned: [{ template_id, t, correct, n }]; templates: { id: { b0, a, c } }
export function calibrate(binned, { min = 50, templates = {}, existing = {} } = {}) {
  const byTid = new Map();
  for (const r of binned) {
    if (!byTid.has(r.template_id)) byTid.set(r.template_id, []);
    const k = Number(r.n_options);
    byTid.get(r.template_id).push({ t: Number(r.t), correct: Number(r.correct) ? 1 : 0, n: Number(r.n), ...(k >= 2 ? { c: 1 / k } : {}) });
  }
  const out = { ...existing };
  const report = [];
  for (const [tid, rows] of byTid) {
    const n = rows.reduce((s, r) => s + r.n, 0);
    const tpl = templates[tid];
    if (!tpl) continue;
    if (n < min) {
      report.push({ tid, n, skipped: true });
      continue;
    }
    const { b } = estimateB(rows, { b0: tpl.b0, a: tpl.a, c: tpl.c });
    out[tid] = { b, a: tpl.a, n };
    report.push({ tid, n, from: tpl.b0, to: b });
  }
  return { calibration: out, report };
}

export function render(calibration) {
  const keys = Object.keys(calibration).sort();
  const body = keys.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(calibration[k])},`).join('\n');
  return (
    '// Generated by scripts/calibrate.mjs from consented anonymous responses. Do not edit by hand.\n' +
    '// templateId: { b: difficulty override, a: discrimination, n: responses used }\n' +
    `export const CALIBRATION = {${keys.length ? '\n' + body + '\n' : ''}};\n`
  );
}

function loadRows(args) {
  if (args.file) {
    const j = JSON.parse(readFileSync(args.file, 'utf8'));
    return Array.isArray(j) && j[0] && j[0].results ? j[0].results : Array.isArray(j) ? j : (j.results ?? []);
  }
  const out = execFileSync(
    'npx',
    ['wrangler', 'd1', 'execute', 'iq-test', args.local ? '--local' : '--remote', '--json', '--command', SQL],
    { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
  );
  const j = JSON.parse(out.slice(out.indexOf('[')));
  return j[0]?.results ?? [];
}

async function main() {
  const argv = process.argv.slice(2);
  const args = { local: argv.includes('--local'), dry: argv.includes('--dry-run') };
  const fi = argv.indexOf('--file');
  if (fi >= 0) args.file = argv[fi + 1];
  const mi = argv.indexOf('--min');
  args.min = mi >= 0 ? Number(argv[mi + 1]) : 50;

  // Template parameters come from the engine; existing overrides from calibration.js.
  const engine = await import(pathToFileURL(join(ROOT, 'public/js/engine.js')).href);
  const templates = {};
  for (const t of engine.TEMPLATES) {
    let c = 0.2;
    try {
      c = 1 / engine.buildItem(t.id, 0).options.length;
    } catch {
      /* keep default */
    }
    templates[t.id] = { b0: t.b, a: t.a ?? 1.3, c };
  }
  let existing = {};
  try {
    existing = (await import(pathToFileURL(OUT).href + '?t=' + Date.now())).CALIBRATION || {};
  } catch {
    /* none yet */
  }

  const rows = loadRows(args);
  const { calibration, report } = calibrate(rows, { min: args.min, templates, existing });
  for (const r of report) {
    console.log(r.skipped ? `${r.tid}: n=${r.n} < ${args.min}, skipped` : `${r.tid}: n=${r.n} b ${r.from} -> ${r.to}`);
  }
  const text = render(calibration);
  if (args.dry) {
    console.log('\n' + text);
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT} (${Object.keys(calibration).length} templates)`);
  }
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  main().catch((e) => {
    console.error(e.message || e);
    process.exit(1);
  });
}
